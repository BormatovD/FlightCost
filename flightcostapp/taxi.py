"""Руление по аэропортам из T-100: время от колодок до колодок минус время в воздухе.

ЗАЧЕМ. Модель брала руление по стандартному циклу ИКАО — 26 минут на
рейс (19 на выруливание, 7 на заруливание) везде. Сверка на сетях
Frontier и Southwest (09.11.2026, research/verify-2026-11) показала, что
это верно для загруженных узлов и завышает блок-время на 7–9 % у
перевозчика, летающего через средние аэропорты: в Бёрбанке или
Мидуэе самолёт рулит 10–12 минут, а не 26.

ЧТО ИЗМЕРЕНО. В T-100 у каждой строки (перевозчик × пара × тип × месяц)
есть RAMP_TO_RAMP и AIR_TIME — в минутах, суммой по рейсам. Их разность
на рейс — руление обоих концов вместе: выруливание в аэропорту вылета
плюс заруливание в аэропорту прилёта. Разделить их по строке нельзя;
по сети — можно: у аэропорта десятки пар, и сумма «t(вылет) + t(прилёт)»
подбирается по всем сразу. t(a) — половина оборота аэропорта: средняя
доля руления, которую он вносит в рейс. Выруливание и заруливание в одном
аэропорту не различаются — для блок-времени и топлива руления нужна
только их сумма на рейс.

ЧЕГО ЭТО НЕ ЕСТЬ. Не время по конкретной полосе и не прогноз в час пик:
среднее за год по всем перевозчикам. Аэропорт с малым числом рейсов не
получает оценки — у него руление по стандарту ИКАО.
"""

from __future__ import annotations

from collections import defaultdict

# Только аэропорты США. В T-100 есть и иностранные концы — рейсы в Европу и
# Азию, — но по ним оценка смещена: у такого аэропорта в выборке одни
# дальнемагистральные рейсы в США, широкофюзеляжные и с удалёнными
# стоянками. 09.11.2026 это дало Франкфурту 19 и Барселоне 18 минут на конец
# вместо ~10 по EUROCONTROL — блок-время FRA–BCN выросло на 9 %, а с ним
# экипаж, ТОиР и владение. Иностранные концы участвуют в подборе (иначе их
# руление легло бы на американский конец), но оценки по ним не выдаются.
US_PREFIXES = ("K", "PA", "PH", "PG", "TJ", "TI")


def is_us(icao: str) -> bool:
    return bool(icao) and icao.upper().startswith(US_PREFIXES)


MIN_DEPARTURES = 300       # рейсов в год через аэропорт, чтобы оценка не шумела
ITERATIONS = 200
CLAMP = (2.0, 25.0)        # половина оборота, мин: вне — ошибка данных, а не аэропорт


def fit(segments, min_departures: int = MIN_DEPARTURES, us_only: bool = True) -> dict[str, tuple[float, int]]:
    """segments: (вылет, прилёт, рейсов, руление на рейс в минутах).

    Возвращает {аэропорт: (половина оборота, мин; рейсов)}. Подбор —
    чередующимися средними: t(a) = средневзвешенное по рейсам через a от
    (руление рейса − t(другого конца)). Это наименьшие квадраты для
    модели t(o) + t(d); шаг вполовину, иначе итерации колеблются."""
    deps = defaultdict(float)
    rows = []
    for o, d, n, taxi in segments:
        if n <= 0 or not (5.0 <= taxi <= 90.0):
            continue
        rows.append((o, d, n, taxi))
        deps[o] += n
        deps[d] += n
    t = {a: 13.0 for a in deps}
    for _ in range(ITERATIONS):
        num, den = defaultdict(float), defaultdict(float)
        for o, d, n, taxi in rows:
            num[o] += n * (taxi - t[d])
            den[o] += n
            num[d] += n * (taxi - t[o])
            den[d] += n
        # Полшага: чистый Якоби на сумме двух неизвестных колеблется.
        t = {a: min(max(0.5 * t[a] + 0.5 * num[a] / den[a], CLAMP[0]), CLAMP[1]) for a in deps}
    return {a: (round(v, 2), int(deps[a])) for a, v in t.items()
            if deps[a] >= min_departures and (not us_only or is_us(a))}


def lookup(store, icao: str, as_of=None) -> float | None:
    if not is_us(icao):
        return None          # оценки вне США смещены (см. US_PREFIXES); стандарт ИКАО
    v = store.value("taxi", icao.upper(), as_of) if store is not None else None
    return float(v) if v else None
