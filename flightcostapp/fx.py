"""Курсы валют для пересчёта сборов в евро.

Курс — не одно число, а несколько источников разного качества, и порядок
между ними важнее самих значений.

1. **Курс из документа.** CRCO публикует ровно тот курс, по которому сам
   выставляет счёт. Для аэронавигации это не приближение, а факт: любой
   другой курс даст расхождение со счётом. Приезжает в домен `fx`
   попутно с ставками.

2. **Справочные курсы ЕЦБ.** Около тридцати валют, ежедневно. Хорошее
   приближение для всего, что публикуется в национальной валюте без
   указания курса.

3. **Привязанные валюты.** Риал Катара жёстко привязан к доллару с 2001
   года, дирхам ОАЭ и саудовский риал тоже. ЕЦБ их не котирует, но курс
   выводится через доллар с точностью до долей процента.

4. **Ничего не нашлось** — правило пропускается с предупреждением.
   Пересчёт по числу из головы недопустим: он выглядит как расчёт, а
   является выдумкой.

Провенанс обязателен. Курс CRCO и курс, выведенный через привязку, — это
величины разной надёжности, и расчёт должен их различать.
"""

from __future__ import annotations

# Валюты с официальной привязкой К ЕВРО. Пересчёт точен по определению.
#
# Два франка КФА покрывают четырнадцать государств Западной и Центральной
# Африки одной константой: паритет 655,957 за евро зафиксирован с введения
# евро и с тех пор не менялся. Для покрытия континента это самый дешёвый
# кусок работы, какой вообще бывает.
PEGS_TO_EUR = {
    "XOF": 655.957,   # франк КФА BCEAO: Бенин, Буркина-Фасо, Кот-д'Ивуар,
                      # Гвинея-Бисау, Мали, Нигер, Сенегал, Того
    "XAF": 655.957,   # франк КФА BEAC: Камерун, ЦАР, Чад, Конго,
                      # Экваториальная Гвинея, Габон
    "KMF": 491.96775, # коморский франк
    "CVE": 110.265,   # эскудо Кабо-Верде
    "BAM": 1.95583,   # конвертируемая марка
    "BGN": 1.95583,   # лев
}

# Курс к доллару для валют с официальной привязкой.
# Не котируются ЕЦБ, но и не плавают: пересчёт через USD точен.
PEGS_TO_USD = {
    "QAR": 3.64,      # с 2001 года
    "AED": 3.6725,    # с 1997 года
    "SAR": 3.75,      # с 1986 года
    "BHD": 0.376,
    "OMR": 0.3845,
    "JOD": 0.709,
    "HKD": None,      # коридор 7.75-7.85, не жёсткая привязка — не выводим
}


def resolve(store, currency: str, as_of) -> tuple[float | None, str]:
    """Курс национальной валюты к евро и происхождение этого курса.

    Возвращает (курс, провенанс). Курс в единицах валюты за один евро,
    как публикует ЕЦБ и как хранит домен `fx`.
    """
    if currency == "EUR":
        return 1.0, "евро"

    row, prov = _best(store, currency, as_of)
    if row is not None:
        return row["value"], prov

    peg_eur = PEGS_TO_EUR.get(currency)
    if peg_eur:
        return peg_eur, "официальный паритет к евро"

    peg = PEGS_TO_USD.get(currency)
    if peg:
        usd = store.value("fx", "USD", as_of)
        if usd:
            return peg * usd, f"выведен через привязку к доллару ({peg} за USD)"

    return None, "курса нет"


# Приоритет источников. Курс, по которому выставлен счёт, всегда вернее
# справочного, даже если справочный свежее. Без явного порядка побеждал бы
# просто более поздний факт.
PRIORITY = {"crco_enroute_rates": 0, "crco_terminal_rates": 0, "fx_rates": 1}


def _best(store, currency: str, as_of):
    """Лучший доступный курс: сначала по приоритету источника, затем по дате.

    Курс — не ставка: он не «действует с и по», а котируется ежедневно.
    Поэтому если на запрошенную дату котировки нет, берётся последняя
    известная до неё, с пометкой о возрасте. Пустой ответ вместо курса
    трёхдневной давности — хуже, чем курс трёхдневной давности.
    """
    from datetime import date, datetime

    rows = store.db.execute(
        """SELECT * FROM facts WHERE domain='fx' AND key=? AND valid_from <= ?
           ORDER BY valid_from DESC, created_at DESC LIMIT 40""",
        (currency, str(as_of)),
    ).fetchall()
    if not rows:
        return None, "курса нет"
    rows.sort(key=lambda r: (PRIORITY.get(r["source_id"], 9), r["valid_from"]),
              reverse=False)
    best = min(rows, key=lambda r: (PRIORITY.get(r["source_id"], 9),
                                    -_ord(r["valid_from"])))
    src = best["source_id"] or ""
    prov = ("курс, применённый CRCO" if src.startswith("crco")
            else "справочный курс ЕЦБ" if src == "fx_rates"
            else f"источник {src}")
    try:
        age = (date.fromisoformat(str(as_of)[:10])
               - date.fromisoformat(best["valid_from"][:10])).days
        if age > 7:
            prov += f", котировке {age} дн."
    except Exception:                                  # noqa: BLE001
        pass
    return best, prov


def _ord(d: str) -> int:
    return int(str(d)[:10].replace("-", ""))


def make_fx(store, as_of, log: list | None = None):
    """Функция курса для charges.evaluate, попутно собирающая провенанс."""
    def fx(currency: str) -> float | None:
        rate, prov = resolve(store, currency, as_of)
        if log is not None:
            log.append({"currency": currency, "rate": rate, "provenance": prov})
        return rate
    return fx
