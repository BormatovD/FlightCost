"""Полоса бенчмарка из отчётности перевозчиков.

ЗАЧЕМ. В витрине рядом с ответом стоит величина без оценки: «11,64 ц за
кресло-километр». Сказать, много это или мало, нечем — полоса `4,5-8`
была взята по памяти, а вердикт на такой полосе есть украшение
(решение 95). Полоса считается из отчётов конкретных перевозчиков, с
годом и средним плечом.

ПОЧЕМУ ВВОД РУЧНОЙ, А НЕ ПАРСЕР. Отчёт — не таблица: у каждого
перевозчика своя разбивка, свои границы сегментов и свои определения.
Группа против пассажирского сегмента, CASK с топливом и без, плечо
средневзвешенное по креслам или по рейсам — всё это меняет число в разы,
и ошибиться здесь легче, чем в извлечении. Мы это уже проходили: строка
ТОиР у Ryanair была верной и означала не то, что мы думали.

Поэтому каждая величина заводится вместе с ОПРЕДЕЛЕНИЕМ и страницей, и
строка без определения не принимается вовсе.

СРЕДНЕЕ ПЛЕЧО ОБЯЗАТЕЛЬНО. На коротком секторе постоянные статьи делятся
на меньшее число кресло-километров, и CASK выше при той же
эффективности. Полоса без плеча несравнима ни с чем.
"""

from __future__ import annotations

import json

from ..store import Fact

# Что принимается. Ключ — величина, значение — её единица и то, чем она
# ОБЯЗАНА сопровождаться. Поле `basis` не украшение: без него «CASK 7,2»
# через год окажется то ли с топливом, то ли без.
# Принимаются ТОЛЬКО НАЗВАННЫЕ В ОТЧЁТЕ величины. CASK, RASK, доход с
# пассажира и среднее плечо не заводятся фактами: они ВЫВОДЯТСЯ, и
# выводит их расчёт — там, где видно и формулу, и подстановку.
#
# Разница не формальная. CASK можно посчитать от операционных расходов, а
# можно от расходов без топлива; доход с пассажира — от выручки сегмента,
# а можно от трафиковой выручки (разница 6,4% у Lufthansa). Храня
# результат, мы храним чей-то выбор и теряем возможность его оспорить;
# храня слагаемые, мы храним документ.
FIELDS = {
    "revenue_eur":   ("EUR", "выручка; границы сегмента в basis"),
    "opex_eur":      ("EUR", "операционные расходы; что включено — в basis"),
    "traffic_revenue_eur": ("EUR", "трафиковая выручка, без прочих доходов"),
    "ask_km":        ("кресло-км", "предельный пассажирооборот"),
    "rpk_km":        ("пасс-км", "выполненный пассажирооборот"),
    "pax":           ("пасс", "перевезено пассажиров"),
    "flights":       ("рейсов", "выполнено рейсов"),
    "load_factor":   ("доля", "пассажирская загрузка"),
    "block_hours":   ("ч", "блок-часы; публикуют немногие"),
    "employees":     ("чел", "среднесписочная численность"),
    "co2_g_pkm":     ("г/пкм", "удельные выбросы на пассажиро-километр"),
    # Топливо и CO₂ — как опубликованы. S7 отчитывается по SASB в
    # гигаджоулях, не в тоннах; перевод в тонны — расчёт с названным
    # коэффициентом теплоты сгорания, а не число в файле (решение 22:
    # ставка хранится как опубликована, пересчёт — слоями).
    "fuel_gj":       ("ГДж", "потреблённое топливо, энергия, SASB TR-AL-110a.3"),
    "fuel_tonnes":   ("т", "потреблённое топливо, масса"),
    "co2_tonnes":    ("т CO₂", "выбросы охвата 1 при производстве полётов"),
    # Статьи операционных расходов, как раскрыты в отчёте о прибылях.
    # Нужны не для CASK, а для сверки СТРУКТУРЫ: наша модель считает те
    # же статьи, и «ТОиР вдвое выше Wizz» было найдено именно так. Границы
    # статьи у каждого отчёта свои — в basis обязательно, что включено.
    "fuel_cost_eur":        ("EUR", "топливо; валюта в currency"),
    "staff_cost_eur":       ("EUR", "персонал"),
    "airport_handling_cost_eur": ("EUR", "аэропортовые сборы и наземное обслуживание"),
    "route_charges_eur":    ("EUR", "аэронавигация"),
    "maintenance_cost_eur": ("EUR", "ТОиР; граница учёта в basis — что капитализировано"),
    "depreciation_eur":     ("EUR", "амортизация, включая право пользования по МСФО 16"),
    # Курс из САМОГО отчёта. Решение 22 задаёт порядок разрешения: из
    # документа, затем ЕЦБ, затем паритет. Здесь первый слой и есть
    # правильный: отчёт пересчитывает свои же показатели этим курсом, и
    # брать другой значит получить величину, которой в документе нет.
    #
    # ВАЖНО, КАКОЙ ИМЕННО. У годовых величин — СРЕДНИЙ за период, а не на
    # отчётную дату: расходы накоплены за год, и курс на 31 декабря к ним
    # не относится. У Аэрофлота разница 2,4% (94,31 против 92,09), у
    # доллара за 2024 год — 9,8%. Граница учёта, та же по природе, что у
    # строки ТОиР.
    "fx_per_eur":    ("за EUR", "курс валюты отчёта к евро; СРЕДНИЙ за период"),
}

def parse(blob: bytes, ctx: dict) -> list[Fact]:
    """YAML или JSON с выписками из отчётов -> факты `carrier_benchmark`.

    Форма записи:

        carrier: LH
        year: 2025
        source: Annual Report 2025, Lufthansa Group
        source_url: https://report.lufthansagroup.com/2025/annual-report/en/
        scope: группа целиком, включая грузовые и технические сегменты
        values:
          revenue_bn: {value: 39.6, basis: "выручка группы, все сегменты"}
          pax_mln:    {value: 135,  basis: "пассажиры Passenger Airlines"}
    """
    import yaml

    docs = [d for d in yaml.safe_load_all(blob.decode("utf-8")) if d]
    if not docs:
        raise ValueError("файл пуст")
    facts, seen = [], 0
    for d in docs:
        for req in ("carrier", "year", "source"):
            if not d.get(req):
                raise ValueError(f"нет обязательного поля {req!r}")
        car, year = str(d["carrier"]).upper(), int(d["year"])
        for name, item in (d.get("values") or {}).items():
            if name not in FIELDS:
                raise ValueError(
                    f"{car}/{year}: величина {name!r} не из списка; "
                    f"допустимо: {', '.join(sorted(FIELDS))}")
            if not isinstance(item, dict) or "value" not in item:
                raise ValueError(f"{car}/{year}/{name}: нужны value и basis")
            basis = (item.get("basis") or "").strip()
            if not basis:
                # Отказ, а не предупреждение: величина без границы учёта
                # неотличима от величины с другой границей, и через год
                # спорить будет не с чем.
                raise ValueError(
                    f"{car}/{year}/{name}: не указан basis — граница учёта. "
                    f"Ожидалось, например: {FIELDS[name][1]}")
            unit = FIELDS[name][0]
            facts.append(Fact(
                domain="carrier_benchmark", key=f"{car}/{year}/{name}",
                valid_from=f"{year}-12-31", value=float(item["value"]),
                unit=unit, currency=item.get("currency", ""),
                value_text=json.dumps({"basis": basis,
                                       "name": d.get("name", ""),
                                       "scope": d.get("scope", ""),
                                       "page": item.get("page", "")},
                                      ensure_ascii=False),
                source_id=ctx["source_id"], artifact_sha=ctx.get("sha"),
                extracted_by=ctx.get("extracted_by", "parser:carrier_benchmark@1"),
                confidence="exact",
                certainty=item.get("certainty", "exact"),
                error_cost=item.get("error_cost"),
                confirm_by=item.get("confirm_by"),
                node="src_carrier_report",
                source_note=f"{d['source']}; {basis}",
                note=d.get("source_url", "")))
            seen += 1
    ctx.setdefault("summary", []).append(
        f"перевозчиков {len({f.key.split('/')[0] for f in facts})}, "
        f"величин {seen}")
    return facts
