"""Разложение величины на почасовую и поцикловую части.

Решение 11 записано про ТОиР, но описывает целый класс величин, и топливо
в него попадает так же: часть расхода висит на времени полёта, часть на
самом факте рейса. Набор высоты и цикл ВПП не зависят от того, летит борт
час или шесть; крейсер зависит целиком.

**Почему плоская ставка неверна не величиной, а формой.** Час полёта на
двухчасовом плече и на шестичасовом стоит по-разному, потому что цикловая
часть делится на разное число часов. Ошибка не случайная, а
систематическая и односторонняя: короткое плечо всегда занижено. На M2
это дало 24% на трёхстах милях по топливу, на M5 — двукратное занижение
на ста двадцати милях по ТОиР. Дважды один и тот же промах в двух разных
статьях — достаточное основание, чтобы механизм существовал один раз.

**Что даёт одна точка и чего не даёт.** Одна точка задаёт УРОВЕНЬ и не
задаёт СТРУКТУРУ: через одну точку проходит бесконечно много прямых.
Поэтому по одной точке доля цикловой части берётся из заготовки, а
подгоняется только уровень, и запись об этом обязательна. Две точки на
РАЗНЫХ плечах задают обе части однозначно. Три и больше — подбор с
остатком, и остаток надо смотреть: если он велик, разложение на две части
не описывает данные, и подгонять третью часть по тем же точкам нельзя.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Split:
    """Величина на рейс как `per_h · блок-часы + per_cycle`.

    Обе части обязательны. `per_cycle = 0` — законное значение, но
    получить его можно только из данных, а не из умолчания: умолчание в
    ноль есть возврат к плоской ставке под другим именем.
    """

    per_h: float
    per_cycle: float
    points: int = 0
    source: str = ""
    structure: str = "measured"      # measured | assumed
    residual: float | None = None    # среднее отклонение подгонки, в единицах
    note: str = ""

    def at(self, block_h: float) -> float:
        """Величина на один рейс этого плеча."""
        return self.per_h * block_h + self.per_cycle

    def per_hour_at(self, block_h: float) -> float:
        """Полная ставка на блок-час — то, с чем сравнивают в отрасли.

        Почасовая составляющая по отдельности вдвое меньше, и показывать
        её как «ставку» — верный способ получить вывод, что модель
        занижает вдвое.
        """
        return self.at(block_h) / block_h if block_h > 0 else 0.0

    @property
    def cycle_share_at(self):
        """Доля цикловой части на заданном плече."""
        return lambda h: (self.per_cycle / self.at(h)) if self.at(h) else 0.0


def from_share(total_per_h: float, cycle_share: float, ref_block_h: float,
               source: str = "заготовка") -> Split:
    """Разложение по заявленной доле цикловой части на опорном плече.

    Так задаётся заготовка: известен порядок полной ставки и примерная
    доля цикловой части у этого класса машин. На опорном плече сумма обеих
    частей равна исходной ставке — это и есть определение опорного плеча.
    """
    return Split(per_h=total_per_h * (1.0 - cycle_share),
                 per_cycle=total_per_h * cycle_share * ref_block_h,
                 source=source, structure="assumed",
                 note=f"доля цикловой {cycle_share:.0%} на плече "
                      f"{ref_block_h:.2f} ч, не измерена")


def fit(points, prior_cycle_share: float | None = None,
        source: str = "") -> Split:
    """Подбор по точкам «плечо в блок-часах → величина на рейс».

    Одна точка — уровень по ней, структура из `prior_cycle_share`, и это
    записывается в `structure="assumed"`. Без доли из заготовки одна точка
    даёт плоскую ставку, то есть ровно ту ошибку, против которой всё это
    написано; поэтому доля обязательна, а не подставляется нулём.

    Две точки на разных плечах — точное решение. Совпадающие плечи двумя
    точками не являются: они уточняют уровень, но не структуру.
    """
    pts = [(float(h), float(y)) for h, y in points if h and h > 0]
    if not pts:
        raise ValueError("нужна хотя бы одна точка «плечо → величина»")

    uniq = sorted({round(h, 3) for h, _ in pts})
    if len(uniq) == 1:
        h = sum(h for h, _ in pts) / len(pts)
        y = sum(y for _, y in pts) / len(pts)
        if prior_cycle_share is None:
            raise ValueError(
                "по точкам одного плеча структура не выводится: задай долю "
                "цикловой части из заготовки или дай точку на другом плече")
        s = from_share(y / h, prior_cycle_share, h, source=source)
        s.points = len(pts)
        s.note = (f"уровень по {len(pts)} точк(ам) на плече {h:.2f} ч; "
                  f"структура из заготовки, доля цикловой "
                  f"{prior_cycle_share:.0%} — НЕ ИЗМЕРЕНА")
        return s

    n = len(pts)
    sx = sum(h for h, _ in pts)
    sy = sum(y for _, y in pts)
    sxx = sum(h * h for h, _ in pts)
    sxy = sum(h * y for h, y in pts)
    det = n * sxx - sx * sx
    per_h = (n * sxy - sx * sy) / det
    per_cycle = (sy - per_h * sx) / n

    resid = (sum(abs(y - (per_h * h + per_cycle)) for h, y in pts) / n
             if n > 2 else 0.0)
    s = Split(per_h=per_h, per_cycle=per_cycle, points=n, source=source,
              structure="measured", residual=resid,
              note=f"подбор по {n} точкам на {len(uniq)} плечах")

    # Отрицательные части — не «маленькая цикловая», а признак того, что
    # точки не описываются этой формой: разный тип операции, разные борта,
    # ошибка в данных. Молча выдать отрицательную ставку значило бы
    # показать подгонку как измерение.
    if s.per_h < 0 or s.per_cycle < 0:
        s.structure = "inconsistent"
        s.note += (f"; ОТРИЦАТЕЛЬНАЯ ЧАСТЬ (почасовая {s.per_h:.1f}, "
                   f"цикловая {s.per_cycle:.1f}) — точки не описываются "
                   f"разложением на две части")
    return s
